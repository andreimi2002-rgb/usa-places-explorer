const dictionaries: Record<Locale, Record<MessageKey, string>> = { en, ro };

export function t(key: MessageKey, vars?: Record<string, string | number>, locale: Locale = getLocale()): string {
  let s = dictionaries[locale][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Category display name: Romanian name when available and locale is ro. */
export function catName(c: { name: string; nameRo: string | null }, locale: Locale = getLocale()): string {
  return locale === "ro" && c.nameRo ? c.nameRo : c.name;
}

export function humanize(s: string): string {
  const out = s.replace(/[_-]+/g, " ");
  return out.charAt(0).toUpperCase() + out.slice(1);
}

export function formatDate(iso: string | null | undefined, locale: Locale = getLocale()): string {
  if (!iso) return "—";
  const d = new Date(iso.length === 10 ? `${iso}T00:00:00Z` : iso);
  return new Intl.DateTimeFormat(locale === "ro" ? "ro-RO" : "en-US", { year: "numeric", month: "short", day: "numeric", timeZone: "UTC" }).format(d);
}
